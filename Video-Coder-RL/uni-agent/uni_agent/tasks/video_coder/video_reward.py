# judge.rubric structured: Video 1 = GT video, Video 2 = the H3 video of the policy's render, then this text with
# {{scene_description}} filled in. The judge gives sub-scores only; structured_video_reward() combines them.
STRUCTURED_JUDGE_PROMPT = """\
You are a strict, professional evaluator of AI-generated videos that reconstruct an animated scene.

A video model turns an untextured 3D animation (a "white model") and a scene description into a realistic video.
You will receive:
1) The scene description, at the end of this message.
2) Video 1: the reference video, made by the video model from a ground-truth animation of the description.
3) Video 2: the candidate video, made by the same video model with the same description and settings, from an
   animation written by the system under evaluation (the one being evaluated).
All people and objects in both videos are AI-generated.

Critical clarifications:
- This is NOT a pixel-level similarity task. The video model invents the appearance on its own, so it differs even
  between two perfect animations. Judge what the underlying animation determines: which objects are present and
  recognizable, where they are, how they move, and how the camera frames them.
- Ignore appearance: textures, colors, materials, lighting, background style, rendering style (stylized versus
  photorealistic), faces and clothing details, audio and image quality. Requirements of that kind in the
  description are not constraints. Do not reward the candidate for looking nicer than the reference.
- Do NOT assume correctness. A required element that is out of frame, hidden, too small, cut off by the frame or not
  recognizable counts as missing. A static video where the description requires action must score low on motion.
- Both videos have the same length: compare timing directly, ignoring offsets under about half a second.
- Video 1 is a reference, not the only valid answer: use it to judge layout, motion and camera, and use the
  description to judge faithfulness.

Required first step (it must appear in the rationale): extract 3-6 hard constraints from the description that
concern visible content: required subjects/objects and their counts, key setting elements, required actions or
motions (with direction or order if given), spatial relations, and camera requirements if the description states any.

Score Video 2 on four dimensions. Each score MUST be exactly one of 0, 0.25, 0.5, 0.75, 1. A score of 1 is rare and
requires full success in that dimension; when torn between two levels, choose the lower one.

1) faithfulness: Video 2 against the description (presence and structure only; it need not match Video 1).
   1: every hard constraint is clearly visible: all required subjects/objects with the right counts, the setting,
      and the required actions and relations.
   0.75: all essential elements are present; one secondary element is missing, simplified or slightly off (for
      example the count of a minor prop).
   0.5: the main subject and setting are there, but one important element is missing or wrong (wrong number of main
      subjects, a required action not performed, a key prop absent).
   0.25: only a few elements of the description can be recognized; the scene is largely not what it asks for.
   0: nothing in Video 2 recognizably depicts the description.

2) layout: Video 2 against Video 1, the spatial arrangement of the scene.
   1: the same main objects in the same arrangement: relative positions, facing directions, relative sizes and
      placement in the setting all match.
   0.75: the same arrangement with small differences in spacing, orientation or scale.
   0.5: recognizably the same arrangement, with one clear difference (a main object in a different place, a clearly
      wrong relative size, a missing or extra main object).
   0.25: only partial correspondence (for example a similar setting but a different arrangement of the main subjects).
   0: an unrelated arrangement, or nothing comparable.

3) motion: Video 2 against Video 1, what moves and how.
   1: the same objects move along the same directions and paths, in the same order, with matching timing.
   0.75: the same motions in the same order, with small differences in path, amplitude, speed or timing.
   0.5: the main motion is present, but one important motion is missing, extra or in the wrong direction, or the
      order or timing clearly differs.
   0.25: only a small part of the motion corresponds, or Video 2 is mostly static while Video 1 shows the main action.
   0: no corresponding motion.
   Set "motion_na": true only if the description requires no action and Video 1 shows no meaningful object motion;
   then output "motion": 0.5 (it is not used). Otherwise "motion_na": false.

4) camera: Video 2 against Video 1, viewpoint, framing and camera movement.
   1: the same viewpoint (side, height, angle), the same shot size and framing of the main subjects, and the same
      camera movement (or both static).
   0.75: the same viewpoint and movement, with small differences in distance, angle or framing.
   0.5: one clear difference (a different shot size, a different viewing angle, or static versus moving) while the
      main subjects are still framed comparably.
   0.25: several differences; the main subjects are framed very differently (for example a close-up versus a wide shot).
   0: the camera does not show the main subjects.

Global rule: if Video 2 is empty, almost entirely blank, broken, or shows nothing recognizable for most of its
duration, every score is 0 and "motion_na" is false.

Rationale: 5-10 short sentences, evidence only (describe what is visible, with approximate times where useful).
- Start with "Constraints:" and list the extracted hard constraints.
- Then give the key comparisons: how Video 2 meets or misses each constraint, and how its layout, motion and
  camera compare with Video 1.

Output ONLY one valid JSON object with exactly these keys, in this order, and nothing else (no markdown):
{"rationale": "<...>", "faithfulness": <score>, "layout": <score>, "motion": <score>, "camera": <score>, \
"motion_na": <true|false>}

Scene description:
{{scene_description}}"""

STRUCTURED_SCORE_KEYS = ("faithfulness", "layout", "motion", "camera")
DEFAULT_STRUCTURED_WEIGHTS: dict[str, float] = {"faithfulness": 0.25, "layout": 0.25, "motion": 0.30, "camera": 0.20}


class Ref2VAConfig(BaseModel):
    """MiniMax-H3 Ref2VA endpoint (SGLang ``/v1/videos``) and the request used for the GT videos."""

    base_urls: list[str] = Field(
        min_length=1,
        description="H3 servers, e.g. [http://h3-node:30010, http://h3-node:30011] (no /v1 suffix). Each job "
        "goes to the server with the fewest jobs in flight from this process; a server that refuses the "
        "connection is skipped. A single `base_url: ...` is accepted too.",
    )
    shared_dir: str = Field(description="Directory visible to this process and to the H3 server (same path).")
    prompt_field: str = Field(
        default="gen_prompt",
        description="metadata field with a per-sample Ref2VA prompt; when absent the prompt is built from "
        "prompt_template and the scene description.",
    )
    prompt_template: str = Field(
        default=DEFAULT_REF2VA_PROMPT_TEMPLATE,
        description="Ref2VA prompt with {{scene_description}} / {{white_model_video}} placeholders; "
        "must be the one the GT videos were made with.",
    )
    request: dict[str, Any] = Field(
        default_factory=lambda: dict(DEFAULT_REF2VA_REQUEST),
        description="Request body fields besides prompt/conditions; must match the GT generation.",
    )
    request_field: str = Field(
        default="gen_request",
        description="metadata field with per-sample request overrides (e.g. the GT's own seconds/target); "
        "its keys replace those of `request`.",
    )
    poll_interval: float = 5.0
    max_poll_errors: int = Field(
        default=5,
        description="Consecutive failed status/download requests tolerated before the job is given up "
        "(a job takes minutes; one network hiccup should not discard it).",
    )
    timeout: float = Field(default=3600.0, description="Seconds from submit to downloaded video.")

    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="before")
    @classmethod
    def _single_base_url(cls, values: Any) -> Any:
        if isinstance(values, dict) and "base_url" in values:
            values = dict(values)
            values["base_urls"] = [values.pop("base_url"), *values.get("base_urls", [])]
        return values


class JudgeConfig(BaseModel):
    """OpenAI-compatible VLM that receives both videos as ``video_url`` parts."""

    base_url: str = Field(description="OpenAI-compatible base URL, e.g. http://h3-node:8000/v1.")
    model: str
    api_key_env: str | None = Field(default=None, description="Name of the env var holding the API key, if any.")
    rubric: Literal["overall", "structured"] = Field(
        default="structured",
        description="overall: one score for the pair (DEFAULT_JUDGE_PROMPT); structured: the judge also gets the "
        "scene description and gives faithfulness / layout / motion / camera sub-scores (STRUCTURED_JUDGE_PROMPT), "
        "combined here with `weights`.",
    )
    prompt: str | None = Field(
        default=None,
        description="Judge prompt; default DEFAULT_JUDGE_PROMPT (overall) or STRUCTURED_JUDGE_PROMPT (structured, "
        "with a {{scene_description}} placeholder).",
    )
    max_score: float = Field(default=1.0, description="Top of the judge's score scale (the default prompt uses 0-1).")
    weights: dict[str, float] = Field(
        default_factory=lambda: dict(DEFAULT_STRUCTURED_WEIGHTS),
        description="rubric structured: weights of faithfulness / layout / motion / camera in the video reward "
        "(renormalized without motion when the judge marks it N/A).",
    )
    temperature: float = 0.0
    max_tokens: int = 1024
    video_transport: Literal["data_url", "file_url"] = Field(
        default="data_url",
        description="data_url: send the bytes base64-encoded; file_url: send file:// paths (judge must see them).",
    )
    timeout: float = 600.0
    proxy: str | None = Field(
        default=None,
        description="HTTP proxy for the judge only, e.g. http://proxy:80 for an external API from a "
        "compute node. The H3 servers are always reached directly.",
    )
    extra_body: dict[str, Any] = Field(
        default_factory=dict,
        description='Extra request fields, e.g. {"modalities": ["text"]} for Qwen Omni models.',
    )
    max_inline_mb: float = Field(
        default=10.0,
        description="Fail early if a base64-encoded video exceeds this many MB (10^6 bytes; DashScope: 10 MB).",
    )
    stream: bool = Field(
        default=False,
        description="Request a streamed (SSE) reply and join the deltas, for APIs that only stream.",
    )

    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="after")
    def _check_weights(self) -> JudgeConfig:
        if set(self.weights) != set(STRUCTURED_SCORE_KEYS) or min(self.weights.values()) < 0:
            raise ValueError(f"judge.weights needs non-negative weights for exactly {list(STRUCTURED_SCORE_KEYS)}")
        if sum(v for k, v in self.weights.items() if k != "motion") <= 0:
            raise ValueError("judge.weights: faithfulness, layout and camera cannot all be 0")
        return self


class VideoRewardConfig(BaseModel):
    """reward = exe_weight * accept_weight * accepted + video_reward_weight * video_reward (the video reward only for
    accepted), with exe_weight = exp(-global_step / T) (T = exe_anneal_steps, by default the total training steps),
    else 1."""

    enabled: bool = True
    gt_field: str = Field(default="gt_video", description="metadata field with the GT video path.")
    accept_weight: float = 1.0
    video_reward_weight: float = Field(
        default=0.5,
        validation_alias=AliasChoices("video_reward_weight", "similarity_weight"),  # similarity_weight: old name
    )
    exe_anneal_steps: PositiveInt | Literal["auto"] | None = Field(
        default="auto",
        description="T of the execution-reward annealing: the acceptance term is scaled by exp(-global_step / T), "
        "so training shifts from getting the script to run towards the video reward. auto: the trainer's total "
        "number of training steps (len(train dataloader) * epochs); an int sets T directly; None turns it off. "
        "Rollouts without a step (validation, standalone runs) are not annealed.",
    )
    faithfulness_gate: float | None = Field(
        default=0.0,
        description="judge.rubric structured: an accepted rollout whose faithfulness is at most this gets reward 0, "
        "as if not accepted (its video does not depict the description); None disables the gate.",
    )
    on_error: Literal["raise", "zero"] = Field(
        default="raise",
        description="raise: fail the rollout (dropped from training); zero: count the video reward as 0.",
    )
    keep_files: bool = Field(default=False, description="Keep white.mp4 / generated.mp4 / judge.json under shared_dir.")
    ref2va: Ref2VAConfig
    judge: JudgeConfig

    model_config = ConfigDict(extra="forbid")


def exe_weight(cfg: VideoRewardConfig, global_step: int | None, total_steps: int | None = None) -> float:
    """Annealing factor of the acceptance term: exp(-global_step / T), 1 when annealing is off or there is no step.

    T is exe_anneal_steps, or with exe_anneal_steps auto the trainer's total_steps."""
    anneal_steps = total_steps if cfg.exe_anneal_steps == "auto" else cfg.exe_anneal_steps
    if not anneal_steps or global_step is None:
        return 1.0
    return math.exp(-global_step / anneal_steps)


def combine_reward(
    cfg: VideoRewardConfig,
    accepted: bool,
    video_reward: float | None,
    faithfulness: float | None = None,
    global_step: int | None = None,
    total_steps: int | None = None,
) -> float:
    """Unaccepted rollouts get 0; accepted ones the (annealed) accept_weight plus the weighted video reward. With a
    faithfulness (rubric structured) at or below faithfulness_gate the video does not depict the description: 0 as
    well."""
    if not accepted or gated_out(cfg, faithfulness):
        return 0.0
    execution = exe_weight(cfg, global_step, total_steps) * cfg.accept_weight
    return execution + cfg.video_reward_weight * float(video_reward or 0.0)


def gated_out(cfg: VideoRewardConfig, faithfulness: float | None) -> bool:
    """rubric structured: the judge found the video unrelated to the description (faithfulness <= gate)."""
    return faithfulness is not None and cfg.faithfulness_gate is not None and faithfulness <= cfg.faithfulness_gate


def parse_score(text: str, max_score: float) -> float:
    """Normalized score in [0, 1] from the judge's reply (JSON, possibly fenced or with extra text)."""
    m = re.search(r'"score"\s*:\s*"?(-?(?:\d+(?:\.\d*)?|\.\d+))', text or "")
    if m is None:
        raise ValueError(f"judge reply has no score: {text[:200]!r}")
    return min(max(float(m.group(1)) / max_score, 0.0), 1.0)


def parse_structured_judgement(text: str) -> dict[str, Any]:
    """Sub-scores (clipped to [0, 1]) and motion_na from a structured judge reply (JSON, possibly fenced or with
    extra text around it); a missing sub-score raises ValueError."""
    text = text or ""
    obj: Any = None
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        try:
            obj = json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            obj = None
    obj = obj if isinstance(obj, dict) else {}
    scores = {}
    for key in STRUCTURED_SCORE_KEYS:
        value = obj.get(key)
        if value is None:
            m = re.search(rf'"{key}"\s*:\s*"?(-?(?:\d+(?:\.\d*)?|\.\d+))', text)
            value = m.group(1) if m else None
        if value is None:
            raise ValueError(f"judge reply has no {key!r}: {text[:200]!r}")
        scores[key] = min(max(float(value), 0.0), 1.0)
    na = obj.get("motion_na")
    if na is None:
        m = re.search(r'"motion_na"\s*:\s*"?(true|false)', text, re.IGNORECASE)
        na = m.group(1) if m else False
    if isinstance(na, str):
        na = na.strip().lower() == "true"
    return {"scores": scores, "motion_na": bool(na)}


def structured_video_reward(scores: dict[str, float], motion_na: bool, weights: dict[str, float]) -> float:
    """Weighted mean of the sub-scores; without motion (weights renormalized) when the judge marks it N/A."""
    keys = [k for k in STRUCTURED_SCORE_KEYS if not (motion_na and k == "motion")]
    return sum(weights[k] * scores[k] for k in keys) / sum(weights[k] for k in keys)


def _client(timeout: float, transport: httpx.AsyncBaseTransport | None, proxy: str | None = None) -> httpx.AsyncClient:
    # Proxy env vars are ignored: in-cluster services must not go through the HTTP proxy, and an
    # external judge gets its proxy explicitly.
    return httpx.AsyncClient(timeout=timeout, trust_env=False, transport=transport, proxy=proxy)


# Ref2VA jobs in flight per server, for this process (the scheduler for base_urls).
_H3_INFLIGHT: collections.Counter[str] = collections.Counter()


def _server_order(urls: list[str]) -> list[str]:
    """Least-loaded first; random among equals so separate processes spread out."""
    return sorted((u.rstrip("/") for u in urls), key=lambda u: (_H3_INFLIGHT[u], random.random()))


async def _submit(client: httpx.AsyncClient, urls: list[str], body: dict[str, Any]) -> tuple[str, str]:
    """Submit to the least-loaded server that accepts the job; return (server, job id).

    The chosen server's in-flight count is taken before the request, so concurrent submissions from
    this process spread over the servers; the caller releases it when the job is done. Only failures
    where the job cannot have been created (no connection, 5xx) move on to the next server: after a
    read timeout the server may already be generating it.
    """
    errors = []
    for base in _server_order(urls):
        _H3_INFLIGHT[base] += 1
        try:
            resp = await client.post(f"{base}/v1/videos", json=body)
        except (httpx.ConnectError, httpx.ConnectTimeout) as e:
            _H3_INFLIGHT[base] -= 1
            errors.append(f"{base}: {type(e).__name__}")
            continue
        except BaseException:
            _H3_INFLIGHT[base] -= 1
            raise
        if resp.status_code >= 500:
            _H3_INFLIGHT[base] -= 1
            errors.append(f"{base}: HTTP {resp.status_code}")
            continue
        try:
            resp.raise_for_status()
            return base, resp.json()["id"]
        except BaseException:
            _H3_INFLIGHT[base] -= 1
            raise
    raise RuntimeError(f"no Ref2VA server accepted the job: {'; '.join(errors)}")


async def _get_with_retries(
    client: httpx.AsyncClient, url: str, max_errors: int, interval: float, sleep
) -> httpx.Response:
    """GET that rides out transient failures (connection errors, timeouts, 5xx) of a long-running job."""
    failures = 0
    while True:
        try:
            resp = await client.get(url)
            if resp.status_code < 500:
                return resp.raise_for_status()
            error = f"HTTP {resp.status_code}"
        except httpx.TransportError as e:
            error = f"{type(e).__name__}: {e}"
        failures += 1
        if failures > max_errors:
            raise RuntimeError(f"GET {url} failed {failures} times in a row; last: {error}")
        logger.warning("Ref2VA: GET %s failed (%s), retry %d/%d", url, error, failures, max_errors)
        await sleep(interval)


async def generate_ref2va(
    cfg: Ref2VAConfig,
    reference_video: Path,
    prompt: str,
    out_path: Path,
    *,
    transport: httpx.AsyncBaseTransport | None = None,
    sleep=None,
    request_overrides: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Submit one Ref2VA job with ``reference_video`` as the reference, wait, and download the result."""
    sleep = sleep or asyncio.sleep
    body = {
        **cfg.request,
        # parquet fills keys a row lacks with None: those must not erase the defaults
        **{k: v for k, v in (request_overrides or {}).items() if v is not None},
        "prompt": prompt,
        "conditions": [{"type": "video", "uri": f"file://{reference_video}", "role": "reference"}],
    }
    t0 = time.monotonic()
    async with _client(min(cfg.timeout, 600.0), transport) as client:
        retry = dict(max_errors=cfg.max_poll_errors, interval=cfg.poll_interval, sleep=sleep)
        base, job_id = await _submit(client, cfg.base_urls, body)  # holds one in-flight slot on base
        try:
            while True:
                status = (await _get_with_retries(client, f"{base}/v1/videos/{job_id}", **retry)).json()
                if status.get("status") == "completed":
                    break
                if status.get("status") == "failed":
                    raise RuntimeError(f"Ref2VA job {job_id} on {base} failed: {json.dumps(status.get('error'))[:300]}")
                if time.monotonic() - t0 > cfg.timeout:
                    raise TimeoutError(f"Ref2VA job {job_id} on {base} not done after {cfg.timeout:.0f}s")
                await sleep(cfg.poll_interval)
            content = await _get_with_retries(client, f"{base}/v1/videos/{job_id}/content", **retry)
        finally:
            _H3_INFLIGHT[base] -= 1
    out_path.write_bytes(content.content)
    return {"job_id": job_id, "server": base, "seconds": round(time.monotonic() - t0, 1)}


def _video_part(path: Path, transport_mode: str, max_inline_mb: float = float("inf")) -> dict[str, Any]:
    if transport_mode == "file_url":
        url = f"file://{path}"
    else:
        encoded = base64.b64encode(path.read_bytes()).decode()
        if len(encoded) > max_inline_mb * 1_000_000:
            raise ValueError(f"{path}: base64 video is {len(encoded) / 1e6:.1f} MB > max_inline_mb={max_inline_mb}")
        url = "data:video/mp4;base64," + encoded
    return {"type": "video_url", "video_url": {"url": url}}


async def judge_video_reward(
    cfg: JudgeConfig,
    reference_video: Path,
    candidate_video: Path,
    description: str = "",
    *,
    transport: httpx.AsyncBaseTransport | None = None,
) -> dict[str, Any]:
    """Ask the VLM to compare the two videos; return the video reward in [0, 1] and the raw reply (rubric structured:
    also the sub-scores and motion_na; `description` fills the prompt's {{scene_description}})."""
    if cfg.rubric == "structured":
        prompt = (cfg.prompt or STRUCTURED_JUDGE_PROMPT).replace("{{scene_description}}", description.strip())
    else:
        prompt = cfg.prompt or DEFAULT_JUDGE_PROMPT
    content = [
        {"type": "text", "text": "Video 1 (reference):"},
        _video_part(reference_video, cfg.video_transport, cfg.max_inline_mb),
        {"type": "text", "text": "Video 2 (candidate):"},
        _video_part(candidate_video, cfg.video_transport, cfg.max_inline_mb),
        {"type": "text", "text": prompt},
    ]
    reply = await _ask_judge(cfg, content, transport)
    if cfg.rubric == "structured":
        parsed = parse_structured_judgement(reply)
        video_reward = structured_video_reward(parsed["scores"], parsed["motion_na"], cfg.weights)
        return {"video_reward": video_reward, **parsed, "judge_reply": reply[:4000]}
    return {"video_reward": parse_score(reply, cfg.max_score), "judge_reply": reply[:1000]}


async def _ask_judge(
    cfg: JudgeConfig, content: list[dict[str, Any]], transport: httpx.AsyncBaseTransport | None
) -> str:
    """One chat completion with the given user content; returns the reply text."""
    headers = {}
    if cfg.api_key_env and os.environ.get(cfg.api_key_env):
        headers["Authorization"] = f"Bearer {os.environ[cfg.api_key_env]}"
    body = {
        "model": cfg.model,
        "messages": [{"role": "user", "content": content}],
        "temperature": cfg.temperature,
        "max_tokens": cfg.max_tokens,
        **cfg.extra_body,
    }
    url = f"{cfg.base_url.rstrip('/')}/chat/completions"
    async with _client(cfg.timeout, transport, cfg.proxy) as client:
        if cfg.stream:
            reply = await _streamed_reply(client, url, {**body, "stream": True}, headers)
        else:
            resp = await client.post(url, json=body, headers=headers)
            resp.raise_for_status()
            reply = resp.json()["choices"][0]["message"].get("content") or ""
    return reply


async def _streamed_reply(client: httpx.AsyncClient, url: str, body: dict, headers: dict) -> str:
    """Join the content deltas of an OpenAI-style SSE stream."""
    parts: list[str] = []
    async with client.stream("POST", url, json=body, headers=headers) as resp:
        resp.raise_for_status()
        async for line in resp.aiter_lines():
            if not line.startswith("data:"):
                continue
            data = line[len("data:") :].strip()
            if data == "[DONE]":
                break
            for choice in json.loads(data).get("choices") or []:
                parts.append((choice.get("delta") or {}).get("content") or "")
    return "".join(parts)


async def score_rollout(
    cfg: VideoRewardConfig,
    render: bytes,
    gt_video: str,
    prompt: str,
    *,
    description: str = "",
    tag: str = "",
    transport: httpx.AsyncBaseTransport | None = None,
    sleep=None,
    request_overrides: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Run the full pipeline for one accepted render; returns the video reward in [0, 1] plus diagnostics.
    `prompt` is the Ref2VA prompt; `description` (the scene description) goes to a structured judge."""
    work = Path(cfg.ref2va.shared_dir) / f"{tag or 'rollout'}-{uuid.uuid4().hex[:8]}"
    work.mkdir(parents=True, exist_ok=True)
    try:
        white, generated = work / "white.mp4", work / "generated.mp4"
        white.write_bytes(render)
        gen = await generate_ref2va(
            cfg.ref2va, white, prompt, generated, transport=transport, sleep=sleep, request_overrides=request_overrides
        )
        judged = await judge_video_reward(cfg.judge, Path(gt_video), generated, description, transport=transport)
        if cfg.keep_files:
            (work / "judge.json").write_text(json.dumps({"gt_video": gt_video, **judged}, ensure_ascii=False, indent=1))
        return {
            **judged,
            "ref2va_job": gen["job_id"],
            "ref2va_server": gen["server"],
            "ref2va_seconds": gen["seconds"],
            "work_dir": str(work) if cfg.keep_files else None,
        }
    finally:
        if not cfg.keep_files:
            shutil.rmtree(work, ignore_errors=True)
